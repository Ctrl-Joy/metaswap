// Exports contract ABIs from Foundry's out/ directory and the local deployment file into
// packages/sdk/src/generated so web + api consume one typed source of truth.
//
//   node packages/sdk/scripts/sync.mjs            (run after `forge build` and the deploy scripts)
//   node packages/sdk/scripts/sync.mjs --abis-only (no deployment file required)
import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const sdkRoot = resolve(here, '..')
const contractsRoot = resolve(sdkRoot, '../contracts')
const outDir = join(contractsRoot, 'out')
const generatedDir = join(sdkRoot, 'src/generated')
const abisOnly = process.argv.includes('--abis-only')

// export name -> Solidity contract name
const CONTRACTS = {
  weth9Abi: 'WETH9',
  testErc20Abi: 'TestERC20',
  multicall3Abi: 'Multicall3',
  v2FactoryAbi: 'MetaSwapV2Factory',
  v2PairAbi: 'MetaSwapV2Pair',
  v2Router02Abi: 'MetaSwapV2Router02',
  v3FactoryAbi: 'MetaSwapV3Factory',
  v3PoolAbi: 'MetaSwapV3Pool',
  nonfungiblePositionManagerAbi: 'NonfungiblePositionManager',
  swapRouter02Abi: 'SwapRouter02',
  quoterV2Abi: 'QuoterV2',
  tickLensAbi: 'TickLens',
  permit2Abi: 'Permit2',
  universalRouterAbi: 'MetaSwapUniversalRouter',
  exclusiveDutchOrderReactorAbi: 'ExclusiveDutchOrderReactor',
  swapRouter02ExecutorAbi: 'SwapRouter02Executor',
}

function findArtifact(name) {
  const preferred = join(outDir, `${name}.sol`, `${name}.json`)
  if (existsSync(preferred)) return preferred
  // fall back to any <Something>.sol/<name>.json
  for (const entry of readdirSync(outDir)) {
    const candidate = join(outDir, entry, `${name}.json`)
    if (statSync(join(outDir, entry)).isDirectory() && existsSync(candidate)) return candidate
  }
  return null
}

if (!existsSync(outDir)) {
  console.error(`No forge output at ${outDir}. Run \`forge build\` in packages/contracts first.`)
  process.exit(1)
}
mkdirSync(generatedDir, { recursive: true })

const missing = []
let abiSource = '// Generated by packages/sdk/scripts/sync.mjs — do not edit.\n\n'
for (const [exportName, contractName] of Object.entries(CONTRACTS)) {
  const file = findArtifact(contractName)
  if (!file) {
    missing.push(contractName)
    abiSource += `export const ${exportName} = [] as const\n\n`
    continue
  }
  const { abi } = JSON.parse(readFileSync(file, 'utf8'))
  abiSource += `export const ${exportName} = ${JSON.stringify(abi, null, 2)} as const\n\n`
}
writeFileSync(join(generatedDir, 'abis.ts'), abiSource)
console.log(`abis.ts: ${Object.keys(CONTRACTS).length - missing.length}/${Object.keys(CONTRACTS).length} contracts`)
if (missing.length) console.warn(`  missing artifacts (empty ABI emitted): ${missing.join(', ')}`)

if (!abisOnly) {
  const deploymentFile = join(contractsRoot, 'deployments/31337.json')
  if (!existsSync(deploymentFile)) {
    console.error(`No deployment at ${deploymentFile}. Run the deploy scripts or pass --abis-only.`)
    process.exit(1)
  }
  const deployment = JSON.parse(readFileSync(deploymentFile, 'utf8'))
  writeFileSync(join(generatedDir, 'deployment.json'), JSON.stringify(deployment, null, 2) + '\n')
  console.log(`deployment.json: ${Object.keys(deployment.contracts ?? {}).length} contracts, ${deployment.tokens?.length ?? 0} tokens`)
}
